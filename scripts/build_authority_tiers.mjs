#!/usr/bin/env node
// 路線圖橫切項「資料權威分級」（批 F1）：data/research/authority_tiers.<日期>.csv → src/data/authorityTiers.ts。
//
//   node scripts/build_authority_tiers.mjs            （npm run data:tiers；build 鏈最前）
//
// 分級只看「鏈接目標是誰」（P0 官方／P1 權威平台／P2 第三方／OWN 本站與姊妹站），不看頁面當下是否可達；
// 規則表之外的網域由 src/lib/authorityTier.ts 的網域型態啟發式（gov／edu／ac 類 → P0）補上，仍不認得的不標。
// 定義見 docs/MAINTENANCE_MANUAL.md §3.8；研究依據 reports/operations/nope-xcut-directhire-links-20261107/research/authority_tiers.md。
// fail-closed：欄位不齊、match／tier 不在枚舉、網域重複、prefix 非 https URL、日期格式錯 → 不產出。輸出只由內容決定。
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const researchDir = join(root, 'data', 'research')
const die = (m) => { console.error(`build_authority_tiers: ${m}`); process.exit(1) }
const files = readdirSync(researchDir).filter((f) => /^authority_tiers\.\d{4}-\d{2}-\d{2}\.csv$/.test(f)).sort()
if (!files.length) die('missing data/research/authority_tiers.<date>.csv')
const file = files.at(-1)

function parseCsv(text) {
  const rows = []
  let row = [], cell = '', quoted = false
  for (let i = 0; i < text.length; i += 1) {
    const ch = text[i]
    if (quoted) {
      if (ch === '"' && text[i + 1] === '"') { cell += '"'; i += 1 } else if (ch === '"') quoted = false
      else cell += ch
    } else if (ch === '"') quoted = true
    else if (ch === ',') { row.push(cell); cell = '' }
    else if (ch === '\n') { row.push(cell); rows.push(row); row = []; cell = '' }
    else if (ch !== '\r') cell += ch
  }
  if (cell || row.length) { row.push(cell); rows.push(row) }
  const [header, ...body] = rows
  return { header, rows: body.filter((r) => r.length > 1).map((r) => Object.fromEntries(header.map((h, i) => [h, (r[i] ?? '').trim()]))) }
}

const { header, rows } = parseCsv(readFileSync(join(researchDir, file), 'utf8'))
if (header.join(',') !== 'domain,match,tier,nameZh,reason,checkedAt') die(`header ${header.join(',')}`)
const MATCH = new Set(['prefix', 'host', 'registrable'])
const TIER = new Set(['P0', 'P1', 'P2', 'OWN'])
const seen = new Set()
for (const r of rows) {
  for (const k of header) if (!r[k]) die(`${r.domain || '?'}: empty ${k}`)
  if (!MATCH.has(r.match)) die(`${r.domain}: match ${r.match}`)
  if (!TIER.has(r.tier)) die(`${r.domain}: tier ${r.tier}`)
  if (!/^\d{4}-\d{2}-\d{2}$/.test(r.checkedAt)) die(`${r.domain}: checkedAt`)
  if (r.match === 'prefix' ? !/^https:\/\/[a-z0-9.-]+\/[^\s]*$/i.test(r.domain) : !/^[a-z0-9.-]+$/i.test(r.domain)) die(`${r.domain}: domain form for ${r.match}`)
  const key = `${r.match}:${r.domain.toLowerCase()}`
  if (seen.has(key)) die(`duplicate ${key}`)
  seen.add(key)
}
// 比對順序：prefix（URL 前綴）→ host（精確主機）→ registrable（含子網域；長網域先比，讓 crs.jsj.edu.cn 先於 jsj.edu.cn）。
const order = { prefix: 0, host: 1, registrable: 2 }
const rules = rows
  .map((r) => ({ domain: r.domain.toLowerCase(), match: r.match, tier: r.tier, nameZh: r.nameZh }))
  .sort((a, b) => order[a.match] - order[b.match] || b.domain.length - a.domain.length || a.domain.localeCompare(b.domain, 'en'))
const counts = { rules: rules.length, byTier: Object.fromEntries(['P0', 'P1', 'P2', 'OWN'].map((t) => [t, rules.filter((r) => r.tier === t).length])), byMatch: Object.fromEntries(['prefix', 'host', 'registrable'].map((m) => [m, rules.filter((r) => r.match === m).length])) }
const ts = `// Generated by scripts/build_authority_tiers.mjs from data/research/${file}. Do not edit by hand.
// 外部鏈接權威分級規則表（P0 官方／P1 權威平台／P2 第三方／OWN 本站）；比對邏輯與網域型態啟發式在 src/lib/authorityTier.ts。
export type AuthorityTier = 'P0' | 'P1' | 'P2' | 'OWN'
export type AuthorityTierMatch = 'prefix' | 'host' | 'registrable'
export interface AuthorityTierRule { domain: string; match: AuthorityTierMatch; tier: AuthorityTier; nameZh: string }
export const authorityTiersSource = ${JSON.stringify({ file, checkedAt: rows.map((r) => r.checkedAt).sort().at(-1), counts })} as const
export const authorityTierRules: readonly AuthorityTierRule[] = ${JSON.stringify(rules, null, 2)}
`
writeFileSync(join(root, 'src', 'data', 'authorityTiers.ts'), ts)
console.log(`wrote src/data/authorityTiers.ts from ${file}: ${JSON.stringify(counts)}`)

// 鏈接年檢基線（data/research/link_check.<日期>.summary.json，由 npm run audit:links -- --report 產出）→ src/data/linkCheckBaseline.ts（About 頁與 test:atlas 用計數）。
const summaries = readdirSync(researchDir).filter((f) => /^link_check\.\d{4}-\d{2}-\d{2}\.summary\.json$/.test(f)).sort()
if (!summaries.length) die('missing data/research/link_check.<date>.summary.json（npm run audit:links -- --report <csv>）')
const summaryFile = summaries.at(-1)
const summary = JSON.parse(readFileSync(join(researchDir, summaryFile), 'utf8'))
if (summary.schema !== 'nope.link-check-summary.v1' || !summary.counts?.urls) die(`${summaryFile}: schema`)
const csvGz = summaryFile.replace('.summary.json', '.csv.gz')
if (!readdirSync(researchDir).includes(csvGz)) die(`missing ${csvGz} next to ${summaryFile}`)
const baseline = { file: summaryFile, csv: csvGz, checkedAt: summary.checkedAt, counts: { urls: summary.counts.urls, domains: summary.counts.domains, byStatus: summary.counts.byStatus, byTier: summary.counts.byTier, broken: summary.broken.length, redirectCrossDomain: summary.redirectCrossDomain.length } }
writeFileSync(join(root, 'src', 'data', 'linkCheckBaseline.ts'), `// Generated by scripts/build_authority_tiers.mjs from data/research/${summaryFile}. Do not edit by hand.
// 全站外部鏈接年檢基線（只有計數；逐條結果在 data/research/${csvGz}）。年檢流程見 docs/MAINTENANCE_MANUAL.md §3.9。
export const linkCheckBaseline = ${JSON.stringify(baseline, null, 2)} as const
`)
console.log(`wrote src/data/linkCheckBaseline.ts from ${summaryFile}: urls ${baseline.counts.urls}, broken ${baseline.counts.broken}`)
