#!/usr/bin/env node
// 路線圖 S4（批 E1）：多語言字串 → 懶載字典與 manifest。
//
//   node scripts/build_i18n.mjs            （npm run data:i18n；build 鏈在 data:overseas 之後）
//
// 讀 src/i18n/locales/zh-Hant.json（來源語言，打包進主包）、src/i18n/locales/en.json（站方翻譯）、
// src/i18n/zh-hans.overrides.json（簡體不能由字形轉換得到的少數鍵，如 meta.htmlLang），寫
//   public/i18n/en.json          en 字典（壓縮；只在切到 en 時載入）
//   public/i18n/zh-Hans.json     zh-Hans 字典（由 zh-Hant 以 scripts/lib/t2s.mjs 字級轉換生成；只轉字形不換用詞）
//   src/data/i18nManifest.ts     版本雜湊（只由內容決定）＋鍵數＋位元組（前端載入時核對鍵數）
// fail-closed：三語鍵集合相等、無空值、佔位符與富文本標記一致、tests/fixtures/zh-hans.fixtures.json 140 條全過，否則不產出。
// 決定性：不含建置時間；重建相同輸入得到相同雜湊。
import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { gzipSync } from 'node:zlib'
import { checkFixtures, t2s } from './lib/t2s.mjs'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const die = (m) => { console.error(`build_i18n: ${m}`); process.exit(1) }
const readJson = (p) => JSON.parse(readFileSync(join(root, p), 'utf8'))

const zhHant = readJson('src/i18n/locales/zh-Hant.json')
const en = readJson('src/i18n/locales/en.json')
const overrides = readJson('src/i18n/zh-hans.overrides.json')
/** 佔位符 {name} 與富文本標記 <b>/<n>/<x>/<code>/<br/>/<a1>… 的簽名；三語必須一致（研究 strings_inventory.md §3 規則 2）。 */
const SIGNATURE_EXCEPTIONS = new Set(['ui.world.institutionLabel'])
export const signature = (s) => {
  const ph = [...String(s).matchAll(/\{(\w+)\}/g)].map((m) => m[1]).sort()
  const tags = [...String(s).matchAll(/<(a\d|b|n|x|code|br)\/?>/g)].map((m) => m[1]).sort()
  return `${ph.join(',')}|${tags.join(',')}`
}

const keys = Object.keys(zhHant).sort((a, b) => a.localeCompare(b, 'en'))
if (keys.length !== new Set(keys).size) die('duplicate keys')
if (JSON.stringify(keys) !== JSON.stringify(Object.keys(zhHant))) die('zh-Hant.json keys must be sorted (en locale order)')
const enKeys = Object.keys(en).sort((a, b) => a.localeCompare(b, 'en'))
if (JSON.stringify(keys) !== JSON.stringify(enKeys)) {
  const onlyZh = keys.filter((k) => !(k in en)), onlyEn = enKeys.filter((k) => !(k in zhHant))
  die(`key sets differ: only zh-Hant ${JSON.stringify(onlyZh.slice(0, 10))} only en ${JSON.stringify(onlyEn.slice(0, 10))}`)
}
for (const k of Object.keys(overrides)) if (!(k in zhHant)) die(`override key not in zh-Hant: ${k}`)
for (const k of keys) {
  if (typeof zhHant[k] !== 'string' || !zhHant[k].trim()) die(`empty zh-Hant value: ${k}`)
  if (typeof en[k] !== 'string' || !en[k].trim()) die(`empty en value: ${k}`)
  if (!SIGNATURE_EXCEPTIONS.has(k) && signature(zhHant[k]) !== signature(en[k])) die(`placeholder/tag mismatch ${k}: zh{${signature(zhHant[k])}} en{${signature(en[k])}}`)
}

const bad = checkFixtures(join(root, 'tests', 'fixtures', 'zh-hans.fixtures.json'))
if (bad.length) die(`zh-Hans fixtures failed (${bad.length}): ${JSON.stringify(bad.slice(0, 5))}`)

const zhHans = {}
for (const k of keys) zhHans[k] = k in overrides ? overrides[k] : t2s(zhHant[k])
for (const k of keys) if (signature(zhHans[k]) !== signature(zhHant[k])) die(`zh-Hans signature drift ${k}`)

const outDir = join(root, 'public', 'i18n')
mkdirSync(outDir, { recursive: true })
const enJson = JSON.stringify(Object.fromEntries(keys.map((k) => [k, en[k]])))
const zhHansJson = JSON.stringify(Object.fromEntries(keys.map((k) => [k, zhHans[k]])))
const zhHantJson = JSON.stringify(Object.fromEntries(keys.map((k) => [k, zhHant[k]])))
writeFileSync(join(outDir, 'en.json'), enJson + '\n')
writeFileSync(join(outDir, 'zh-Hans.json'), zhHansJson + '\n')

const version = createHash('sha256').update(zhHantJson).update('\n').update(zhHansJson).update('\n').update(enJson).digest('hex').slice(0, 12)
const manifest = {
  version,
  basePath: '/i18n',
  sourceLocale: 'zh-Hant',
  lazyLocales: ['zh-Hans', 'en'],
  counts: {
    keys: keys.length,
    overrides: Object.keys(overrides).length,
    bytes: { 'zh-Hant': Buffer.byteLength(zhHantJson), 'zh-Hans': Buffer.byteLength(zhHansJson), en: Buffer.byteLength(enJson) },
    gzipBytes: { 'zh-Hant': gzipSync(Buffer.from(zhHantJson)).length, 'zh-Hans': gzipSync(Buffer.from(zhHansJson)).length, en: gzipSync(Buffer.from(enJson)).length },
  },
}
writeFileSync(join(root, 'src', 'data', 'i18nManifest.ts'), `// Generated by scripts/build_i18n.mjs. Do not edit by hand.\nexport const i18nManifest = ${JSON.stringify(manifest, null, 2)} as const\n`)
console.log(`wrote public/i18n/{en,zh-Hans}.json (${keys.length} keys; gzip zh-Hant ${manifest.counts.gzipBytes['zh-Hant']} B, zh-Hans ${manifest.counts.gzipBytes['zh-Hans']} B, en ${manifest.counts.gzipBytes.en} B) version ${version}`)
