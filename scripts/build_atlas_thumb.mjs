// 首頁「全球學科地圖」特色卡的靜態縮圖（2026-11-08 批 G9）：由 public/data/atlas/world-atlas.json 的陸地輪廓與機構點生成，
// 決定性輸出 src/data/atlasThumb.ts（同一份 atlas 永遠得到同一份縮圖）。陸地：座標取整、Douglas–Peucker 容差 1.4、丟掉
// 外接框面積 < 40 的小島；點：機構座標取整去重。只用色系變數著色（.atlas-land／.atlas-dot），紙色、墨色都看得清。
//   node scripts/build_atlas_thumb.mjs
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const atlas = JSON.parse(readFileSync(join(root, 'public/data/atlas/world-atlas.json'), 'utf8'))
const { width, height } = atlas.projection

function rings(d) {
  const out = []
  for (const part of d.split('Z').map((s) => s.trim()).filter(Boolean)) {
    const nums = part.match(/-?\d+(?:\.\d+)?/g)?.map(Number) ?? []
    const pts = []
    for (let i = 0; i + 1 < nums.length; i += 2) pts.push([nums[i], nums[i + 1]])
    if (pts.length >= 3) out.push(pts)
  }
  return out
}
function simplify(pts, tol) {
  if (pts.length < 4) return pts
  const keep = new Uint8Array(pts.length); keep[0] = keep[pts.length - 1] = 1
  const stack = [[0, pts.length - 1]]
  while (stack.length) {
    const [a, b] = stack.pop()
    const [ax, ay] = pts[a], [bx, by] = pts[b]
    const len = Math.hypot(bx - ax, by - ay) || 1
    let max = 0, idx = -1
    for (let i = a + 1; i < b; i += 1) { const d = Math.abs((bx - ax) * (ay - pts[i][1]) - (ax - pts[i][0]) * (by - ay)) / len; if (d > max) { max = d; idx = i } }
    if (max > tol && idx > 0) { keep[idx] = 1; stack.push([a, idx], [idx, b]) }
  }
  return pts.filter((_, i) => keep[i])
}
const paths = []
for (const d of atlas.land) {
  for (const ring of rings(d)) {
    const xs = ring.map((p) => p[0]), ys = ring.map((p) => p[1])
    if ((Math.max(...xs) - Math.min(...xs)) * (Math.max(...ys) - Math.min(...ys)) < 40) continue
    // 閉合環的首尾是同一點，單段 Douglas–Peucker 會退化：在離起點最遠的點切成兩段各自簡化
    let far = 0, best = -1
    for (let i = 1; i < ring.length; i += 1) { const d = Math.hypot(ring[i][0] - ring[0][0], ring[i][1] - ring[0][1]); if (d > best) { best = d; far = i } }
    const halves = [...simplify(ring.slice(0, far + 1), 1.4), ...simplify(ring.slice(far), 1.4).slice(1)]
    const s = halves.map(([x, y]) => [Math.round(x), Math.round(y)]).filter((p, i, arr) => i === 0 || p[0] !== arr[i - 1][0] || p[1] !== arr[i - 1][1])
    if (s.length >= 3) paths.push(`M${s.map((p) => p.join(' ')).join('L')}Z`)
  }
}
const dots = [...new Set(atlas.institutions.map((i) => `${Math.round(i.x)},${Math.round(i.y)}`))].sort()
const land = paths.join('')
const version = createHash('sha256').update(land + dots.join(';')).digest('hex').slice(0, 12)
const out = `// Generated by scripts/build_atlas_thumb.mjs from public/data/atlas/world-atlas.json. Do not edit by hand.\n// 首頁全球學科地圖縮圖（批 G9）：簡化陸地輪廓＋機構點（取整去重）。\nexport const atlasThumb = ${JSON.stringify({ version, atlasVersion: atlas.version, width, height, land, dots: dots.join(' '), institutions: atlas.institutions.length, subjects: atlas.subjects.length })} as const\n`
writeFileSync(join(root, 'src/data/atlasThumb.ts'), out)
console.log(JSON.stringify({ version, rings: paths.length, dots: dots.length, bytes: out.length }))
