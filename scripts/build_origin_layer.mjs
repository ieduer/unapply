#!/usr/bin/env node
// 路線圖 S4（批 E2）：起點分支（資格／範圍）的資料層 → 前端懶載 payload 與生成檔。
//
//   node scripts/build_origin_layer.mjs            （npm run data:origins；build 鏈在 data:overseas 之後、data:i18n 之前）
//
// 讀 public/data/overseas/regions/<slug>.json（批 S3 產出）與 data/research/origin_sources.<日期>.json（研究會話核過的官方頁子集），寫
//   public/data/overseas/qualifications.json   S3 `qualificationsListed` token → 機構 id 清單＋ gaokaoPolicy=accepted 的機構 id（結果頁／海外頁計數用，gzip ≤ 20 KiB）
//   src/data/originSources.ts                  官方頁清單（url → 標題／網域／狀態／核對日／是否上鏈接）；只有 verified＋https＋同網域才 live
//   src/data/originManifest.ts                 版本雜湊（只由內容決定）＋計數（前端載入時核對）
// 原則：資格只用於「保留」標示（校方頁面寫明接受），永不劃掉任何機構；not_stated 一律未知。語言不進這一層。fail-closed。
import { createHash } from 'node:crypto'
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { gzipSync } from 'node:zlib'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const die = (m) => { console.error(`build_origin_layer: ${m}`); process.exit(1) }
const regionDir = join(root, 'public', 'data', 'overseas', 'regions')
const researchDir = join(root, 'data', 'research')
const sourceFiles = readdirSync(researchDir).filter((f) => /^origin_sources\.\d{4}-\d{2}-\d{2}\.json$/.test(f)).sort()
if (!sourceFiles.length) die('missing data/research/origin_sources.<date>.json')
const research = JSON.parse(readFileSync(join(researchDir, sourceFiles.at(-1)), 'utf8'))
if (research.schema !== 'nope.origin-sources.v1' || !Array.isArray(research.sources) || research.sources.length !== research.count) die('origin_sources schema/count')

const index = JSON.parse(readFileSync(join(root, 'public', 'data', 'overseas', 'index.json'), 'utf8'))
const regionFiles = readdirSync(regionDir).filter((f) => f.endsWith('.json')).sort()
const byToken = new Map()
const gaokaoAccepted = []
let institutions = 0
const EMAIL = /[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}/
for (const file of regionFiles) {
  const region = JSON.parse(readFileSync(join(regionDir, file), 'utf8'))
  if (region.version !== index.version) die(`${file} version ≠ index`)
  for (const inst of region.institutions) {
    institutions += 1
    if (!/^R[IG]\d+$/.test(inst.id)) die(`unexpected institution id ${inst.id}`)
    if (inst.gaokaoPolicy === 'accepted') gaokaoAccepted.push(inst.id)
    for (const token of inst.qualifications.listed) {
      if (typeof token !== 'string' || !token.trim() || token.length > 60 || EMAIL.test(token)) die(`bad token ${token} in ${inst.id}`)
      if (!byToken.has(token)) byToken.set(token, [])
      byToken.get(token).push(inst.id)
    }
  }
}
if (institutions !== index.institutions.length) die(`institutions ${institutions} ≠ index ${index.institutions.length}`)
const tokens = Object.fromEntries([...byToken.entries()].sort(([a], [b]) => a.localeCompare(b, 'en')).map(([token, ids]) => [token, ids.sort()]))
const payload = { version: '', overseasVersion: index.version, generatedAt: index.generatedAt, institutions, tokens, gaokaoAccepted: gaokaoAccepted.sort() }
const version = createHash('sha256').update(JSON.stringify(payload)).digest('hex').slice(0, 12)
payload.version = version
const json = JSON.stringify(payload)
const gz = gzipSync(Buffer.from(json)).length
if (gz > 20 * 1024) die(`qualifications.json gzip ${gz} > 20 KiB`)
writeFileSync(join(root, 'public', 'data', 'overseas', 'qualifications.json'), json)

// 官方頁清單：只有 verified＋https＋最終網域在記錄網域之下才上鏈接。
const hostUnder = (url, domain) => { try { const h = new URL(url).hostname.toLowerCase(); const d = String(domain).toLowerCase(); return h === d || h.endsWith(`.${d}`) } catch { return false } }
const sources = {}
for (const s of research.sources) {
  if (!['verified', 'blocked', 'needs_review', 'not_found'].includes(s.status)) die(`status ${s.status} ${s.url}`)
  if (EMAIL.test(JSON.stringify(s))) die(`email in source ${s.url}`)
  const live = s.status === 'verified' && /^https:\/\//.test(s.url) && hostUnder(s.finalUrl || s.url, s.domain)
  sources[s.url] = { title: s.title, domain: s.domain, status: s.status, live, fetchedAt: String(s.fetchedAt).slice(0, 10), reason: s.reason || '' }
}
const sourcesTs = `// Generated by scripts/build_origin_layer.mjs from data/research/${sourceFiles.at(-1)}. Do not edit by hand.\n// 起點資格制度與港澳臺→大陸官方管道的官方頁：只有 live=true（verified＋https＋同網域）才渲染為鏈接，其餘只列標題與網域（研究 origin_branch_design.md §7 留待人工覆核）。\nexport type OriginSourceStatus = 'verified' | 'blocked' | 'needs_review' | 'not_found'\nexport interface OriginSource { title: string; domain: string; status: OriginSourceStatus; live: boolean; fetchedAt: string; reason: string }\nexport const originSources: Record<string, OriginSource> = ${JSON.stringify(sources, null, 2)}\n`
writeFileSync(join(root, 'src', 'data', 'originSources.ts'), sourcesTs)
const manifest = {
  version, overseasVersion: index.version, path: '/data/overseas/qualifications.json', generatedAt: index.generatedAt,
  counts: { institutions, tokens: Object.keys(tokens).length, institutionsWithTokens: new Set(Object.values(tokens).flat()).size, gaokaoAccepted: gaokaoAccepted.length, sources: Object.keys(sources).length, sourcesLive: Object.values(sources).filter((s) => s.live).length, gzipBytes: gz },
}
writeFileSync(join(root, 'src', 'data', 'originManifest.ts'), `// Generated by scripts/build_origin_layer.mjs. Do not edit by hand.\nexport const originManifest = ${JSON.stringify(manifest, null, 2)} as const\n`)
console.log(`wrote public/data/overseas/qualifications.json (${(json.length / 1024).toFixed(0)} KiB, gzip ${(gz / 1024).toFixed(1)} KiB) version ${version}; sources ${manifest.counts.sources} (live ${manifest.counts.sourcesLive})`)
console.log(JSON.stringify(manifest.counts))
